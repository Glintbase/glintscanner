// Helper Query Methods
export function getAllChecks(): CheckDefinition[] {
  return ALL_CHECKS;
}

export function getCheckById(id: string): CheckDefinition | undefined {
  return ALL_CHECKS.find(c => c.id === id);
}

export function getChecksForLayer(layer: LayerId): CheckDefinition[] {
  return ALL_CHECKS.filter(c => c.layer === layer);
}

export function getBonusChecks(): CheckDefinition[] {
  return ALL_CHECKS.filter(c => c.isBonus);
}

export function getChecksForSpec(spec: 'ars' | 'strict' | 'core'): CheckDefinition[] {
  if (spec === 'core') {
    // 12 Essential checks
    const coreIds = new Set([
      'robots-ai-policy-quality',
      'ard-catalog',
      'brand-search-accuracy',
      'content-no-js',
      'anti-spa-404',
      'llms-txt-exists',
      'markdown-negotiation',
      'openapi-spec',
      'mcp-server-manifest',
      'mcp-tools-listing',
      'auth-bearer-token-support',
      'api-json-schemas',
    ]);
    return ALL_CHECKS.filter(c => coreIds.has(c.id));
  }
  return ALL_CHECKS;
}
